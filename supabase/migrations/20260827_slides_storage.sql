-- 파일을 Storage로 — Worker가 존재한 이유의 나머지 절반.
--
-- ── 무엇이 사라지는가 ─────────────────────────────────────────────────────────────────
-- ppt에서 파일은 Durable Object 안에 **1 MiB 조각으로 쪼개져** 살았다. Durable Object에는
-- 큰 값을 넣을 수 없어서, 업로드는 조각마다 라우트를 왕복했고 (`PPT_FILE_KINDS`가 만들어
-- 내던 청크 라우트 일습), 다운로드는 그것을 다시 이어 붙였다. 저장소가 진짜 객체 저장소가
-- 되면 그 코드가 통째로 없어진다 — 이번 합치기에서 가장 큰 감소다.
--
-- 함께 사라지는 것이 하나 더 있다. ppt에는 로그인이 없었으므로 "이 브라우저의 사본"이라는
-- 개념이 있었다: localStorage/IndexedDB에 두고 서버와 병합했다. 계정이 생기면 사본은 하나다.
--
-- ── 버킷 셋, 전부 비공개 ──────────────────────────────────────────────────────────────
-- 악보와 콘티는 저작권이 있는 자료이고 설교 PPT는 아직 전하지 않은 말씀이다. 공개 버킷은
-- URL을 아는 누구나 읽을 수 있다는 뜻이고, 그 URL은 화면·로그·공유 링크로 새어 나간다.
-- 그래서 전부 비공개로 두고 **짧은 TTL의 서명 URL로만** 내보낸다.
INSERT INTO storage.buckets (id, name, public)
VALUES
    ('kccp-conti',  'kccp-conti',  false),   -- 찬양팀이 올리는 콘티 PDF
    ('kccp-sheets', 'kccp-sheets', false),   -- 콘티에서 잘라 낸 악보 쪽 이미지
    ('kccp-decks',  'kccp-decks',  false)    -- 완성된 예배 슬라이드와 그 재료
ON CONFLICT (id) DO NOTHING;

-- 정책은 두지 않는다. 나머지 표와 같은 처리다: 데이터 통로는 service_role로 도는 엣지
-- 함수뿐이고, 누가 무엇에 닿을 수 있는지는 auth.ts가 TypeScript로 판정한다. anon/authenticated
-- 키로는 이 버킷들의 목록조차 볼 수 없다 — storage.objects 의 RLS가 기본으로 켜져 있고
-- 정책이 없으면 전부 거부이기 때문이다.
--
-- 서명 URL은 그 판정을 통과한 뒤에 함수가 발급한다. 발급된 링크는 TTL 동안 자격 없이도
-- 열리므로 **짧게** 준다 (기본 5분, ai-proxy 쪽 상수와 같은 자리에서 관리).

